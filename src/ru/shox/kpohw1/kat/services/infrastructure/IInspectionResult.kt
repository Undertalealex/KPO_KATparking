package ru.shox.kpohw1.kat.services.infrastructure

// результат технического осмотра
// интерфейс отделён от реализации, чтобы вызывающий код зависел только от
// принято/отклонено, а не от конкретного класса, а также для дальнейшего
// возможного расширения разных результатов для разных транспортов
interface IInspectionResult {

    // true - единица принята на баланс
    val isAccepted: Boolean
    // причина отказа иначе null для успешного осмотра
    val reason: String?
}
